template <int mod = (int)1e9 + 7> struct modint {
    int x;
    modint(int y = 0) : x((y % mod + mod) % mod) { }
    friend modint operator ^ (modint a, long long b) {
        modint r = 1;
        for(; b; b >>= 1, a *= a) {
            if(b & 1) {
                r *= a;
            } 
        }
        return r;
    }
    friend modint operator - (modint a) {
        return modint(0) - a;
    }
    friend modint operator ! (modint a) {
        return a ^ (mod - 2);
    }
    modint& operator /= (modint const& b) {
        return *this *= !b;
    }
    friend modint operator + (modint a, modint const& b) {
        return a += b;
    }
    friend modint operator - (modint a, modint const& b) {
        return a -= b;
    }
    friend modint operator * (modint a, modint const& b) {
        return a *= b;
    }
    friend modint operator / (modint a, modint const& b) {
        return a /= b;
    }
    friend bool operator != (const modint &a, const modint b) {
        return a.x != b.x;
    }
    friend bool operator == (const modint &a, const modint b) {
        return a.x == b.x;
    }
    modint& operator *= (modint const& b) {
        x = 1ll * x * b.x % mod;
        return *this;
    }
    friend ostream& operator << (ostream& os, modint const& a) {
        return os << a.x;
    }
    modint& operator += (modint const& b) {
        x += b.x;
        x = (x >= mod) ? x - mod : x;
        return *this;
    }
    modint& operator -= (modint const& b) {
        x = x >= b.x ? x - b.x : x - b.x + mod;
        return *this;
    }
};

using mint = modint <>;

main() {
    ios_base::sync_with_stdio(false);
    cin.tie(nullptr);
    chrono::steady_clock::time_point begin = chrono::steady_clock::now();

    int t;
    cin >> t;
    while(t--) {
        int n;
        cin >> n;
        vector<int> a(n);
        
        for(int i = 0; i < n; i++) {
            cin >> a[i];
        }

        int ans = 0;
        for(int m = 1; m <= 3; m++) {
            mint cur = 0;
            bool ok = true;
            for(int i = 0; i < n; i++) {
                if(m > a[i]) {
                    ok = false;
                    break;
                }

                cur = (cur * 2 + (a[i] - m) * (i & 1 ? -1 : 1));
            }
            if(!ok)
                continue;

            mint mul = ((mint(2)^n) + (n & 1 ? 1 : -1));
            mint a0 = cur / mul;
            // cerr << mul << " " << cur << " " << a0 << endl;
            vector<int> r(n);
            r[0] = a0.x;
            for(int i = 1; i < n; i++) {
                r[i] = (a[i - 1] - m) - 2 * r[i - 1];
                if(r[i] < 0) {
                    ok = false;
                    break;
                }
            }
            // cerr << "dbg: " << endl;
            // for(int i = 0; i < n; i++)
            //     cerr << r[i] << " ";
            // cerr << endl;
            if(!ok)
                continue;
            
            
            for(int i = 0; i < n; i++) {
                if(2 * r[i] + r[(i + 1) % n] != (a[i] - m))
                    ok = false;
            }
            if(!ok)
                continue;

            int mn = 1e9;
            for(int i = 0; i < n; i++) {
                mn = min(mn, r[i]);
            }
            ans = max(ans, m + 3 * mn);
        }
        cout << ans << endl;
    }

    chrono::steady_clock::time_point end = chrono::steady_clock::now();
    cerr << "Time elapsed: " << chrono::duration_cast<chrono::milliseconds>(end - begin).count() << " ms" << endl;
}